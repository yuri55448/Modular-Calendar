const MAP: Record<string, string> = {
  "惊": "驚", "蛰": "蟄", "谷": "穀", "处": "處", "满": "滿", "种": "種",
  "腊": "臘", "闰": "閏", "节": "節", "灯": "燈", "阳": "陽", "龙": "龍",
  "头": "頭", "开": "開", "岁": "歲", "复": "復", "轩": "軒", "辕": "轅",
  "诞": "誕", "观": "觀", "华": "華", "药": "藥",
  "马": "馬", "鸡": "雞", "猪": "豬",
};

export function t(s: string): string {
  let out = "";
  for (const ch of s) out += MAP[ch] ?? ch;
  return out;
}
